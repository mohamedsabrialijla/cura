/** @param {string} locale */
export function dashboardCopy(locale) {
    return DASHBOARD_COPY[resolveLocale(locale)];
}

/**
 * @param {string} locale
 * @param {string} key — key in crumbs object
 * @param {string} [param] — dynamic segment e.g. master_data category slug
 */
export function dashboardBreadcrumb(locale, key, param) {
    const loc = resolveLocale(locale);
    const copy = DASHBOARD_COPY[loc];

    if (key === "master_data_category" && param) {
        const slug = String(param).toLowerCase();
        const label = MASTER_DATA_LABELS[slug]?.[loc] || param;
        return loc === "ar" ? `إدارة ${label}` : `${label} Management`;
    }

    if (key === "master_data_object" && param) {
        const name = String(param).charAt(0).toUpperCase() + String(param).slice(1);
        return loc === "ar" ? `إدارة ${name}` : `${name} Management`;
    }

    return copy.crumbs[key] || key;
}

/** @param {string} locale */
export function dashboardT(locale, path) {
    const copy = dashboardCopy(locale);
    const parts = String(path).split(".");
    let node = copy;
    for (const p of parts) {
        if (!node || typeof node !== "object") return path;
        node = node[p];
    }
    return typeof node === "string" ? node : path;
}
